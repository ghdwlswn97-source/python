# f-string
# 문자열을 만드는 따옴표(' or ")앞에 알파벳 f(or F)를 붙여줌
# 문자열 내부에서 변수를 넣고 싶은 자리에 {변수명}을 적는다
print('두 수의 합은', 3+5, '입니다.')
print('두 수의 합은 ' + str(3+5) + ' 입니다.')
print('두 수의 합은 %d 입니다.'%(3+5))
print(f'두 수의 합은 {3+5} 입니다.')